"""The shipped store index: thousands of models, available without a network.

``localcode/hub/data/catalog.json.gz`` is generated by ``scripts/build_catalog.py``
from the Hugging Face model index (see that script for the selection rules) and
holds one row per installable model — the popular part of the Hub that
``llama-server``, ``mlx-lm`` or the image runtime can actually load.

The file stores **facts only** (downloads, licence, file kinds, upstream
repository, parameter count…).  The trust score is computed from those facts at
display time by :mod:`localcode.hub.trust`, so the rubric can be changed, tested
and argued with without regenerating anything.

Loading is lazy and cached: the first call reads ~1 MB of gzip, later calls hit
an in-process index.  A missing or damaged file is not an error — the store then
falls back to the staff picks, exactly as it does offline.
"""

from __future__ import annotations

import gzip
import json
import logging
import threading
from pathlib import Path
from typing import Any, Iterable

from localcode.hub import store_search
from localcode.hub.trust import Trust, evaluate, evaluate_row

log = logging.getLogger(__name__)

DATA_PATH = Path(__file__).resolve().parent / "data" / "catalog.json.gz"

_lock = threading.Lock()
_cache: dict[str, Any] | None = None
_index_cache: tuple[list[dict[str, Any]], dict[str, set[int]]] | None = None
_by_repo: dict[str, dict[str, Any]] = {}
_trust_cache: dict[str, Trust] = {}


def _load(path: Path | None = None) -> dict[str, Any]:
    global _cache, _by_repo, _index_cache
    with _lock:
        if _cache is not None and path is None:
            return _cache
        target = path or DATA_PATH
        payload: dict[str, Any] = {"version": 0, "generatedAt": None, "models": []}
        if target.exists():
            try:
                with gzip.open(target, "rb") as fh:
                    payload = json.loads(fh.read().decode("utf-8"))
            except Exception as exc:  # noqa: BLE001 - a broken index must not break the store
                log.warning("Nie udało się wczytać katalogu modeli (%s): %s", target, exc)
                payload = {"version": 0, "generatedAt": None, "models": []}
        models = [m for m in (payload.get("models") or []) if isinstance(m, dict) and m.get("repo")]
        payload["models"] = models
        if path is None:
            _cache = payload
            _index_cache = None
            _by_repo = {str(m["repo"]).lower(): m for m in models}
        return payload


def load_index(path: Path) -> dict[str, Any]:
    """Read one index file without touching the process-wide cache.

    The test suite replaces :data:`DATA_PATH` with an empty index so that unit
    tests do not depend on thousands of shipped rows; the few tests that check
    the shipped file itself use this instead.
    """
    return _load(path)


def reset_cache() -> None:
    """Drop the in-process index (tests point :data:`DATA_PATH` elsewhere)."""
    global _cache, _by_repo, _trust_cache, _index_cache
    with _lock:
        _cache = None
        _index_cache = None
        _by_repo = {}
        _trust_cache = {}


def generated_at() -> str | None:
    """When the shipped index was built (ISO-8601), or ``None`` when missing."""
    return _load().get("generatedAt")


def count() -> int:
    return len(_load().get("models") or [])


def all_models() -> list[dict[str, Any]]:
    """Every row of the index (do not mutate: the rows are shared)."""
    return list(_load().get("models") or [])


def get(repo: str) -> dict[str, Any] | None:
    """One row by repository id, or ``None``."""
    _load()
    return _by_repo.get((repo or "").lower())


def trust_of(entry: dict[str, Any]) -> Trust:
    """The trust score for an index row (cached per repository)."""
    repo = str(entry.get("repo") or "")
    hit = _trust_cache.get(repo)
    if hit is not None:
        return hit
    base_models = {"models": [entry["baseModel"]]} if entry.get("baseModel") else None

    trust = evaluate(
        repo,
        author=entry.get("author"),
        downloads=entry.get("downloads"),
        downloads_all_time=entry.get("downloadsAllTime"),
        likes=entry.get("likes"),
        license_id=entry.get("license"),
        license_name=entry.get("licenseName"),
        file_summary=entry.get("files"),
        base_models=base_models,
        last_modified=entry.get("updatedAt"),
        created_at=entry.get("createdAt"),
        gated=entry.get("gated"),
        curated=bool(entry.get("curated")),
        author_info=entry.get("authorInfo") or author_info(repo.partition("/")[0]),
    )
    _trust_cache[repo] = trust
    return trust


def author_info(name: str | None) -> dict[str, Any] | None:
    """What the Hub said about an author when the index was built, if anything.

    Verified organisation and follower count: the "is this a real creator"
    half of the trust score for authors that are not on our list of
    laboratories and trusted converters (see ``localcode/hub/trust.py``).
    """
    if not name:
        return None
    authors = _load().get("authors") or {}
    hit = authors.get(name)
    if hit is None:
        lowered = name.lower()
        hit = next((v for k, v in authors.items() if k.lower() == lowered), None)
    return dict(hit) if isinstance(hit, dict) else None


def trust_for(repo: str, *, hub: dict[str, Any] | None = None, curated: bool = False) -> Trust:
    """Score any repository, using the index when it knows it.

    The shipped index carries the licence and the file list, so a model that is
    in it scores on full information; anything else — a repository found by a
    live search, or one typed in by hand — is scored on whatever that search
    returned, and its reasons say as much.
    """
    row = get(repo)
    if row is not None:
        if curated and not row.get("curated"):
            row = {**row, "curated": True}
            return evaluate_row(row, curated=True)
        return trust_of(row)
    hub = hub or {}
    return evaluate(
        repo,
        author=hub.get("author") or repo.partition("/")[0],
        downloads=hub.get("downloads"),
        downloads_all_time=hub.get("downloadsAllTime"),
        likes=hub.get("likes"),
        tags=hub.get("tags") or (),
        last_modified=hub.get("updatedAt"),
        gated=hub.get("gated"),
        curated=curated,
        author_info=hub.get("authorInfo") or author_info(repo.partition("/")[0]),
    )


def _prepare(entry: dict[str, Any]) -> dict[str, Any]:
    """Cache the tokenised haystacks on the row (computed once per process)."""
    if "_name_tokens" not in entry:
        name, other = store_search.haystacks(entry)
        entry["_name_tokens"] = name
        entry["_other_tokens"] = other
    return entry


def _build_index() -> tuple[list[dict[str, Any]], dict[str, set[int]]]:
    """``(rows, {token: row numbers})`` — the inverted index used by :func:`search`.

    Without it a query with a typo costs a Levenshtein comparison against every
    token of every row (hundreds of thousands), which was visible as a
    quarter-second pause per keystroke.  With it, a misspelt word is matched
    against the *vocabulary* once — a few thousand comparisons — and only the
    rows that contain a surviving token are ever scored.
    """
    rows = list(_load().get("models") or [])
    index: dict[str, set[int]] = {}
    for number, entry in enumerate(rows):
        _prepare(entry)
        for token in set(entry["_name_tokens"]) | set(entry["_other_tokens"]):
            index.setdefault(token, set()).add(number)
    return rows, index


def _index() -> tuple[list[dict[str, Any]], dict[str, set[int]]]:
    """The inverted index, built once.

    Built *outside* the module lock on purpose: :func:`_build_index` calls
    :func:`_load`, which takes that same lock, and ``threading.Lock`` is not
    reentrant — holding it here deadlocked the first search.
    """
    global _index_cache
    cached = _index_cache
    if cached is not None:
        return cached
    built = _build_index()
    with _lock:
        if _index_cache is None:
            _index_cache = built
        return _index_cache


def _candidates(word: str, index: dict[str, set[int]]) -> set[int]:
    """Rows containing a token that matches ``word`` exactly, by prefix or typo."""
    hits: set[int] = set(index.get(word, ()))
    budget = 0 if len(word) <= 2 else (1 if len(word) <= 7 else 2)
    for token, rows in index.items():
        if token == word:
            continue
        if len(word) >= 3 and token.startswith(word):
            hits |= rows
            continue
        if budget and abs(len(token) - len(word)) <= budget and token[0] == word[0]:
            if store_search.close_enough(word, token):
                hits |= rows
    return hits


def search(
    query: str = "",
    *,
    category: str | None = None,
    fmt: str | None = None,
    min_score: int = 0,
    official_only: bool = False,
    include_excluded: bool = False,
    limit: int | None = None,
) -> list[dict[str, Any]]:
    """Index rows matching a free-text query and the filters, best first.

    A query is understood rather than matched literally (see
    :mod:`localcode.hub.store_search`): typos, Polish wording and intent
    ("mały model do kodu") all work, and results come back ordered by how well
    they answer the question.  Without a query the index's own popularity order
    is kept, which is what a store should show by default.
    """
    intent = store_search.parse(query)
    rows = _load().get("models") or []
    scored: list[tuple[float, dict[str, Any]]] = []
    out: list[dict[str, Any]] = []

    if not intent.is_empty and intent.words:
        # Narrow to the rows that can possibly match before scoring anything.
        rows_all, index = _index()
        candidates: set[int] | None = None
        for word in intent.words:
            hits = _candidates(word, index)
            candidates = hits if candidates is None else (candidates & hits)
            if not candidates:
                return []
        rows = [rows_all[n] for n in sorted(candidates or ())]

    for entry in rows:
        if category and entry.get("category") != category:
            continue
        if fmt and entry.get("format") != fmt:
            continue
        if official_only and entry.get("provenance") != "official":
            continue
        trust = None
        if min_score or intent.wants_trusted or not include_excluded:
            trust = trust_of(entry)
            if not include_excluded and trust.excluded:
                continue
            if min_score and trust.score < min_score:
                continue
        if intent.is_empty:
            out.append(entry)
            if limit is not None and len(out) >= limit:
                break
            continue
        value = store_search.score(_prepared(entry), intent, trust=trust.score if trust else None)
        if value is not None:
            scored.append((value, entry))

    if intent.is_empty:
        return out
    scored.sort(key=lambda pair: -pair[0])
    ranked = [entry for _, entry in scored]
    return ranked[:limit] if limit is not None else ranked


def _prepared(entry: dict[str, Any]) -> dict[str, Any]:
    """The row with its cached token lists, for :mod:`store_search`."""
    _prepare(entry)
    return entry


def repos() -> Iterable[str]:
    for entry in _load().get("models") or []:
        yield str(entry["repo"])
