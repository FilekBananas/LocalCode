#: The file that actually ships, regardless of the empty index the suite
#: installs for every other test (see ``tests/conftest.py``).
SHIPPED = Path(store_data.__file__).resolve().parent / "data" / "catalog.json.gz"
shipped = pytest.mark.skipif(not SHIPPED.exists(),
                             reason="katalog nie został jeszcze wygenerowany")


def shipped_models() -> list[dict[str, Any]]:
    return list(store_data.load_index(SHIPPED).get("models") or [])


@shipped
def test_the_shipped_index_is_large_and_well_formed() -> None:
    payload = store_data.load_index(SHIPPED)
    assert len(payload.get("models") or []) >= 1000, \
        "sklep ma pokazywać tysiące modeli, nie kilkadziesiąt"
    assert payload.get("generatedAt")


@shipped
def test_every_shipped_row_can_be_shown_and_installed() -> None:
    for entry in shipped_models():
        repo = entry.get("repo")
        assert repo and "/" in repo, entry
        assert entry.get("format") in ("gguf", "mlx"), repo
        assert entry.get("category") in CATEGORIES, repo
        assert entry.get("name"), repo
        assert isinstance(entry.get("files"), dict), repo
        assert entry.get("provenance") in ("official", "trusted", "community", "unknown"), repo


@shipped
def test_every_shipped_row_scores_without_raising() -> None:
    for entry in shipped_models():
        trust = store_data.trust_of(entry)
        assert 0 <= trust.score <= 100, entry["repo"]
        assert trust.label


@shipped
def test_the_shipped_index_describes_most_of_what_it_shows() -> None:
    """The first screens of the store must read like a shop, not a database."""
    top = shipped_models()[:1000]
    described = [m for m in top if str(m.get("tagline") or "").strip()]
    # Not 100%: a newly added shelf (speech, video) arrives before its
    # descriptions are written, and a generated line is better than a wrong one.
    assert len(described) >= 850, f"tylko {len(described)}/1000 modeli ma opis"


@shipped
def test_the_shipped_index_has_no_duplicate_repositories() -> None:
    repos = [m["repo"] for m in shipped_models()]
    assert len(repos) == len(set(repos))
