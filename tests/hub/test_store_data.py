def test_search_matches_name_repo_and_tagline(index) -> None:
    index([
        row("Qwen/Qwen3-Coder-30B", name="Qwen3 Coder 30B", category="kodowanie"),
        row("google/gemma-4-12b", name="Gemma 4 12B", tagline="Rozmowa i pisanie tekstów."),
    ])
    assert [m["repo"] for m in store_data.search("coder")] == ["Qwen/Qwen3-Coder-30B"]
    assert [m["repo"] for m in store_data.search("rozmowa")] == ["google/gemma-4-12b"]
    assert len(store_data.search("")) == 2


def test_search_is_accent_and_case_insensitive(index) -> None:
    index([row("speakleash/Bielik-11B", name="Bielik 11B",
               tagline="Model po polsku — rozumie język i skróty.")])
    assert store_data.search("JĘZYK")
    assert store_data.search("jezyk")


def test_search_requires_every_word(index) -> None:
    index([row("Qwen/Qwen3-Coder-30B", name="Qwen3 Coder 30B"),
           row("google/gemma-4-12b", name="Gemma 4 12B", publisher="Google")])
    assert len(store_data.search("qwen coder")) == 1
    assert store_data.search("qwen gemma") == []


def test_filters_narrow_the_result(index) -> None:
    index([
        row("Qwen/Coder", category="kodowanie", provenance="official", author="Qwen"),
        row("mlx-community/Chat", category="czat", format="mlx", provenance="trusted"),
        row("nick/Unknown", category="czat", provenance="unknown", author="nick",
            downloads=5, likes=0, license=None),
    ])
    assert [m["repo"] for m in store_data.search(category="kodowanie")] == ["Qwen/Coder"]
    assert [m["repo"] for m in store_data.search(fmt="mlx")] == ["mlx-community/Chat"]
    assert [m["repo"] for m in store_data.search(official_only=True)] == ["Qwen/Coder"]
    assert "nick/Unknown" not in [m["repo"] for m in store_data.search(min_score=40)]


def test_limit_caps_the_result(index) -> None:
    index([row(f"org/model-{i}") for i in range(10)])
    assert len(store_data.search(limit=3)) == 3
    assert len(store_data.search(min_score=1, limit=3)) == 3


