"""The shipped model index (``localcode.hub.store_data``).

Two things matter here: that a broken or missing index degrades to "the store
has no extra models" instead of an exception on the user's first screen, and
that the shipped file really does describe installable models — the data is
checked as strictly as the code, because it is regenerated by a script and a
mistake there would reach the user silently.
"""

from __future__ import annotations

import gzip
import json
from pathlib import Path
from typing import Any

import pytest

from localcode.hub import store_data
from localcode.hub.catalog import CATEGORIES


def write_index(path: Path, models: list[dict[str, Any]]) -> Path:
    payload = {"version": 1, "generatedAt": "2026-09-26T00:00:00Z",
               "source": "Hugging Face", "models": models}
    with gzip.open(path, "wb") as fh:
        fh.write(json.dumps(payload, ensure_ascii=False).encode("utf-8"))
    return path


def row(repo: str, **kw: Any) -> dict[str, Any]:
    entry = {
        "repo": repo,
        "format": "gguf",
        "author": repo.partition("/")[0],
        "name": repo.partition("/")[2],
        "category": "czat",
        "paramsB": 8.0,
        "quant": "Q4_K_M",
        "sizeBytes": 4_700_000_000,
        "downloads": 1000,
        "likes": 10,
        "license": "apache-2.0",
        "files": {"known": True, "safe": True, "pickle": [], "code": []},
        "caps": ["tools"],
        "provenance": "trusted",
        "publisher": "Qwen (Alibaba)",
        "rank": 0,
        "authorInfo": {"verified": True, "followers": 100, "isOrg": False},
    }
    entry.update(kw)
    return entry


@pytest.fixture
def index(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """Point the loader at a temporary index built from ``models``."""
    def build(models: list[dict[str, Any]]):
        path = write_index(tmp_path / "catalog.json.gz", models)
        monkeypatch.setattr(store_data, "DATA_PATH", path)
        store_data.reset_cache()
        return path
    yield build
    store_data.reset_cache()


