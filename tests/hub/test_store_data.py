def test_a_missing_index_is_an_empty_store_not_an_error(tmp_path, monkeypatch) -> None:
    monkeypatch.setattr(store_data, "DATA_PATH", tmp_path / "nie-ma.json.gz")
    store_data.reset_cache()
    assert store_data.count() == 0
    assert store_data.all_models() == []
    assert store_data.get("cokolwiek") is None
    assert store_data.generated_at() is None
    store_data.reset_cache()


def test_a_damaged_index_is_reported_and_ignored(tmp_path, monkeypatch, caplog) -> None:
    broken = tmp_path / "catalog.json.gz"
    broken.write_bytes(b"to nie jest gzip")
    monkeypatch.setattr(store_data, "DATA_PATH", broken)
    store_data.reset_cache()
    with caplog.at_level("WARNING"):
        assert store_data.count() == 0
    assert any("katalog" in r.message.lower() for r in caplog.records)
    store_data.reset_cache()


def test_rows_without_a_repository_are_dropped(index) -> None:
    index([row("Qwen/A"), {"name": "bez repo"}, row("Qwen/B")])
    assert store_data.count() == 2


def test_lookup_ignores_case(index) -> None:
    index([row("Qwen/Qwen3-8B-GGUF")])
    assert store_data.get("qwen/qwen3-8b-gguf") is not None
    assert store_data.get("Qwen/Qwen3-8B-GGUF")["format"] == "gguf"


