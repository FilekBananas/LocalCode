def test_trust_is_computed_from_the_row_and_cached(index) -> None:
    index([row("Qwen/Qwen3-8B-GGUF", author="Qwen", downloads=2_000_000, likes=800)])
    entry = store_data.get("Qwen/Qwen3-8B-GGUF")
    first = store_data.trust_of(entry)
    assert first.score > 60
    assert store_data.trust_of(entry) is first          # cached, not recomputed


def test_trust_uses_the_stored_file_summary(index) -> None:
    index([
        row("a/clean"),
        row("a/pickled", files={"known": True, "safe": False,
                                "pickle": [".bin"], "code": []}),
    ])
    clean = store_data.trust_of(store_data.get("a/clean"))
    pickled = store_data.trust_of(store_data.get("a/pickled"))
    assert clean.score > pickled.score


